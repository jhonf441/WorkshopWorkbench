      // -- validation of the whole job --
      function tcValidate(tc, opts) {
        var errs = [];
        var st = tc.ctx.machine.getSt();
        var area = tc.ctx.cut.area();
        var lim = tc.ctx.cut.limits();
        var correction = tc.ctx.cut.correction();
        tcSyncLayers(tc);
        if (!tcShapesInCutOrder(tc).length) errs.push(i18nT('cuts.there_are_no_shapes_or_all'));
        if (!st || st.mode !== "Laser") errs.push(i18nT('cuts.the_machine_is_not_in_laser'));
        if (!(opts && opts.frame)) tcCutGuard(tcCutGuardInput(tc)).forEach(function (e) { errs.push(e); }); // zone, material and focus (41-cuts-job-guard.js); framing does not cut
        if (!correction) errs.push(i18nT('cuts.there_is_no_known_laser_correction'));
        if (!area) errs.push(i18nT('cuts.the_cut_area_of_this_mode'));
        tc.data.shapes.forEach(function (s, i) {
          var name = i18nT('cuts.shape', { n: i + 1 });
          if (!(s.power > 0 && s.power <= 100)) errs.push(i18nT('cuts.power_1_100', { name: name }));
          if (!(s.speed > 0)) errs.push(i18nT('cuts.speed_0', { name: name }));
          if (!(s.passes >= 1 && s.passes <= 20)) errs.push(i18nT('cuts.passes_1_20', { name: name }));
          var b = tcBBox([s]);
          if (!b) return errs.push(i18nT('cuts.invalid_geometry', { name: name }));
          if (area && (b.xmin < area.xmin - 0.001 || b.xmax > area.xmax + 0.001 || b.ymin < area.ymin - 0.001 || b.ymax > area.ymax + 0.001))
            errs.push(i18nT('cuts.goes_outside_the_cut_area', { name: name }));
          if (lim && correction && (b.xmin + correction.cx < lim.xmin || b.xmax + correction.cx > lim.xmax || b.ymin + correction.cy < lim.ymin || b.ymax + correction.cy > lim.ymax))
            errs.push(i18nT('cuts.with_the_laser_correction_it_goes', { name: name }));
          var ph = tcClampHits(tc, s);
          if (ph.length) {
            var prl = tc.ctx.data.clamps ? tc.ctx.data.clamps() : [];
            errs.push(i18nT('cuts.goes_over', { name: name, list: ph.map(function (k) { return (prl[k] && prl[k].name) || i18nT('common.a_clamp'); }).join(", ") }));
          }
        });
        return errs;
      }

      function tcEstimate(tc) {
        var t = 0, pos = null;
        tcShapesInCutOrder(tc).forEach(function (s) {
          var p = tcShapePath(s);
          if (!p.length) return;
          if (pos) t += Math.hypot(p[0].x - pos.x, p[0].y - pos.y) / TC_TRAVEL_FEED;
          t += (tcPathLen(p) * s.passes) / s.speed;
          pos = p[p.length - 1];
        });
        return t; // minutos
      }

      // -- trabajo de corte --
      function tcBuildJob(tc) {
        var correction = tc.ctx.cut.correction();
        tcSyncLayers(tc);
        var order = tcShapesInCutOrder(tc);
        var maxPct = order.reduce(function (m, s) { return Math.max(m, s.power); }, 0);
        var f3 = function (v) { return v.toFixed(3); };
        var txt =
          "; Workshop - SIMPLE CUTS (" + order.length + " shapes, " + tc.data.layers.length + " layers), generated by WorkshopJog " + tzLocalTime() + "\n" +
          "; Shapes in bed coordinates (beam); machine = point + laser correction X" + correction.cx + " Y" + correction.cy + " (G53).\n" +
          "; Diode laser " + tjLaserWatts + " W, M452 R255: S = % x 2.55. Travel with S0.\n" +
          'M98 P"0:/sys/workshop/macros/cutguard.g" S' + maxPct + "   ; aborts and cancels the job if anything is not right\n" +
          "G90\n";
        var airOn = false, curLayer = null;
        order.forEach(function (s, i) {
          var L = tcLayerById(tc, s.layer);
          if (L !== curLayer) {
            curLayer = L;
            txt += "; ---- layer " + L.name + ": " + L.power + " % " + L.speed + " mm/min x" + L.passes + (L.air ? ", air" : ", no air") + "\n";
            if (L.air && !airOn) { txt += "M42 P7 S1   ; air assist ON\nG4 P500\n"; airOn = true; }
            else if (!L.air && airOn) { txt += "M400\nM42 P7 S0   ; air assist OFF\n"; airOn = false; }
          }
          var pts = tcShapePath(s).map(function (p) { return { x: p.x + correction.cx, y: p.y + correction.cy }; });
          var S = (s.power * 2.55).toFixed(1);
          txt += "; shape " + (tc.data.shapes.indexOf(s) + 1) + ": " + tcDescribeGcode(s) + " | " + s.power + " % " + s.speed + " mm/min x" + s.passes + "\n";
          for (var k = 0; k < s.passes; k++) {
            txt += "G53 G1 X" + f3(pts[0].x) + " Y" + f3(pts[0].y) + " F" + TC_TRAVEL_FEED + " S0\n";
            for (var j = 1; j < pts.length; j++) txt += "G53 G1 X" + f3(pts[j].x) + " Y" + f3(pts[j].y) + " F" + s.speed + " S" + S + "\n";
          }
        });
        txt += "M400\n";
        if (airOn) txt += "M42 P7 S0   ; air assist OFF\n";
        return txt;
      }

      function tcStartJob(tc, file, text, okMsg, alStart) {
        return tzStartFile(file, text) // 22-start-file.js
          .then(function () {
            tc.jobStep = null;
            if (alStart) alStart();
            tcSetMsg(tc, okMsg, true);
          })
          .catch(function (e) {
            tcSetMsg(tc, i18nT('common.not_started', { err: e && e.message ? e.message : e }), false);
          });
      }

