      // writes ONE file with all the jobs shifted to their place; it is not started: it is opened in the preview
      function tvVisCreateFileBoard(tvs) {
        if (!tvs.board.length) return;
        var rv = tvVisCheckBoard(tvs);
        if (!rv.well) {
          tvs.boardOk = false;
          tvs.boardMsg = i18nT('tv.board_fix_first');
          tvVisRender(tvs);
          return;
        }
        tvs.boardMsg = i18nT('tv.board_building');
        tvs.boardOk = true;
        tvVisRender(tvs);
        Promise.all(tvs.board.map(function (it) {
          return fetch("/machine/file/" + encodeURI("0:/gcodes/" + it.path), { cache: "no-store" }).then(function (r) {
            if (!r.ok) throw new Error(it.path + ": HTTP " + r.status);
            return r.text();
          });
        })).then(function (texts) {
          var parts = ["; Workshop - BOARD: " + tvs.board.length + " jobs placed together, generated by WorkshopJog " + tzLocalTime()];
          var av = { rel: 0, g53: 0, g92: 0, g10: 0, macros: 0, inch: 0 };
          texts.forEach(function (t, i) {
            var it = tvs.board[i];
            var d = tvShiftGcode(t, it.dx, it.dy);
            ["rel", "g53", "g92", "g10", "macros", "inch"].forEach(function (k) { av[k] += d.notices[k]; });
            parts.push("; ===== " + it.path + " moved X" + it.dx + " Y" + it.dy + " (" + d.notices.moved + " moves) =====");
            parts.push(d.text);
          });
          var nombre = "Workshop/board_" + tvVisStampLocal(tvs) + ".gcode";
          tvs.boardNotices = [];
          if (av.rel) tvs.boardNotices.push(i18nT('tv.board_w_rel', { n: av.rel }));
          if (av.g53) tvs.boardNotices.push(i18nT('tv.board_w_g53', { n: av.g53 }));
          if (av.g92 || av.g10) tvs.boardNotices.push(i18nT('tv.board_w_g92', { n: av.g92 + av.g10 }));
          if (av.macros) tvs.boardNotices.push(i18nT('tv.board_w_macros', { n: av.macros }));
          if (av.inch) tvs.boardNotices.push(i18nT('tv.board_w_inch'));
          return fetch("/machine/directory/" + encodeURI("0:/gcodes/Workshop"), { method: "PUT" }).catch(function () {}).then(function () {
            return fetch("/machine/file/" + encodeURI("0:/gcodes/" + nombre), {
              method: "PUT",
              headers: { "Content-Type": "application/octet-stream" },
              body: parts.join("\n") + "\n",
            });
          }).then(function (r) {
            if (!r.ok) throw new Error("HTTP " + r.status);
            tvs.boardFile = nombre;
            tvs.boardOk = true;
            tvs.boardMsg = i18nT('tv.board_created', { f: nombre });
            tvVisRender(tvs);
          });
        }).catch(function (e) {
          tvs.boardOk = false;
          tvs.boardMsg = String((e && e.message) || e);
          tvVisRender(tvs);
        });
      }

      function tvVisVerFileBoard(tvs) {
        if (!tvs.boardFile) return;
        var file = tvs.boardFile;
        tvs.board = [];
        tvs.boardFile = null;
        tvs.files.push({ path: file, size: 0, date: "" });
        tvs.sel = file;
        tvs.boardMsg = "";
        tvVisRead(tvs);
      }

      function tvVisDrawBoard(tvs, node, w) {
        if (!tvs.board.length) return;
        var rv = tvCheckBoxes(tvs.board.map(tzBind(tvVisBoxOf, tvs)), tvVisAreaBoard(tvs), 2);
        var sw = w / 300;
        tvs.board.forEach(function (it, i) {
          var c = tvVisCorrectionOf(tvs, it.prev);
          var key = [it.path, Math.round(w * 10), c.cx, c.cy, it.prev.vertices].join("|");
          if (!it.g || it.gkey !== key) {
            var g = document.createElementNS("http://www.w3.org/2000/svg", "g");
            (it.prev.segments || []).forEach(function (r) {
              var pts = [];
              for (var k = 0; k < r.p.length; k += 2) pts.push((r.p[k] - c.cx) + "," + -(r.p[k + 1] - c.cy));
              var el = document.createElementNS("http://www.w3.org/2000/svg", "polyline");
              el.setAttribute("points", pts.join(" "));
              el.setAttribute("fill", "none");
              el.setAttribute("stroke", r.w ? it.color : "#9e9e9e");
              el.setAttribute("stroke-opacity", r.w ? 0.95 : 0.3);
              el.setAttribute("stroke-width", r.w ? sw * 1.4 : sw * 0.6);
              if (!r.w) el.setAttribute("stroke-dasharray", w / 150 + " " + w / 150);
              g.appendChild(el);
            });
            it.g = g;
            it.gkey = key;
          }
          it.g.setAttribute("transform", "translate(" + it.dx + "," + -it.dy + ")");
          node("g", {}).appendChild(it.g);
          var b = tvVisBoxOf(tvs, it);
          var bad = rv.outside.indexOf(i) >= 0 || rv.crosses.some(function (x) { return x[0] === i || x[1] === i; });
          node("rect", { x: b.xmin, y: -b.ymax, width: b.xmax - b.xmin, height: b.ymax - b.ymin, fill: "none", stroke: bad ? "#ef5350" : it.color, "stroke-width": sw * 1.2, "stroke-dasharray": w / 120 + " " + w / 160 });
          node("text", { x: b.xmin + w / 200, y: -b.ymax - w / 150, "font-size": w / 60, fill: bad ? "#ef9a9a" : it.color }).textContent = (i + 1) + ". " + it.path.split("/").pop();
        });
      }

      // points the magnet of the map can stick to: corners, edge middles, centre and outline of what is on the map
      function tvVisPointsMagnetOf(tvs, p, c, dx, dy, nombre) {
        var out = [];
        var b = p.bbox;
        if (!b) return out;
        var x0 = b.xmin - c.cx + dx, x1 = b.xmax - c.cx + dx, y0 = b.ymin - c.cy + dy, y1 = b.ymax - c.cy + dy;
        [[x0, y0, "bottom left corner"], [x1, y0, "bottom right corner"], [x1, y1, "top right corner"], [x0, y1, "top left corner"],
          [(x0 + x1) / 2, y0, "bottom middle"], [(x0 + x1) / 2, y1, "top middle"], [x0, (y0 + y1) / 2, "left middle"], [x1, (y0 + y1) / 2, "right middle"],
          [(x0 + x1) / 2, (y0 + y1) / 2, "centre"]].forEach(function (q) {
          out.push({ x: q[0], y: q[1], name: nombre + ": " + i18nT('tv.snap_' + q[2].replace(/ /g, "_")) });
        });
        (p.hull || []).forEach(function (q) {
          out.push({ x: q[0] - c.cx + dx, y: q[1] - c.cy + dy, name: nombre + ": " + i18nT('tv.snap_outline') });
        });
        return out;
      }

      function tvVisSnapPoints(tvs) {
        var out = [];
        if (tvs.prev) out = out.concat(tvVisPointsMagnetOf(tvs, tvs.prev, tvVisCorrectionOf(tvs, tvs.prev), 0, 0, tvs.sel.split("/").pop()));
        tvs.board.forEach(function (it) { out = out.concat(tvVisPointsMagnetOf(tvs, it.prev, tvVisCorrectionOf(tvs, it.prev), it.dx, it.dy, it.path.split("/").pop())); });
        return out;
      }

      // ---------- the map ----------
      // Layers of a Laser / CNC job: the runs that share power + feed (laser) or depth (CNC), in the order they appear
      function tvVisKeyGroup(tvs, r) {
        if (tvs.prev.mode === "Laser") return Math.round((r.v || 0) * 100) + "|" + (r.fd || 0);
        if (tvs.prev.mode === "CNC") return String(r.v);
        return "";
      }

      function tvVisArmGroups(tvs) {
        tvs.prev.groups = [];
        tvs.prev.indexGroup = {};
        if (!tvs.prev || (tvs.prev.mode !== "Laser" && tvs.prev.mode !== "CNC")) return;
        var byKey = {};
        (tvs.prev.segments || []).forEach(function (r) {
          if (!r.w) return;
          var k = tvVisKeyGroup(tvs, r);
          var g = byKey[k];
          if (!g) {
            g = byKey[k] = { key: k, n: tvs.prev.groups.length, color: tvs.COLORS[tvs.prev.groups.length % tvs.COLORS.length], dist: 0, time: 0, v: r.v, fd: r.fd || 0 };
            tvs.prev.groups.push(g);
          }
          for (var i = 2; i < r.p.length; i += 2) g.dist += Math.hypot(r.p[i] - r.p[i - 2], r.p[i + 1] - r.p[i - 1]);
          if (r.t && r.t.length > 1) g.time += r.t[r.t.length - 1] - r.t[0];
        });
        tvs.prev.indexGroup = byKey;
      }

      function tvVisGroupOf(tvs, r) {
        return tvs.prev && tvs.prev.indexGroup && r.w ? tvs.prev.indexGroup[tvVisKeyGroup(tvs, r)] || null : null;
      }

      function tvVisColorOf(tvs, r) {
        if (!r.w) return "#9e9e9e";
        var gr = tvVisGroupOf(tvs, r);
        if (gr && tvs.colorBy === "layers" && tvs.prev.groups.length > 1) return gr.color;
        if (tvs.prev.mode === "CNC") return ttDepthColor(tvs.prev.stats && tvs.prev.stats.z_min < 0 ? r.v / tvs.prev.stats.z_min : 0);
        return ttPowerColor(Math.round(r.v * 10) / 10);
      }

      function tvvisforma_points(tvs) {
        // frame outline in HEAD coordinates of the machine (the job's own), before the pointer shift
        if (!tvs.prev || !tvs.prev.bbox) return [];
        var b = tvs.prev.bbox;
        if (tvs.shape === "frame") return [[b.xmin, b.ymin], [b.xmax, b.ymin], [b.xmax, b.ymax], [b.xmin, b.ymax], [b.xmin, b.ymin]];
        var h = (tvs.prev.hull || []).slice();
        if (h.length < 3) return [[b.xmin, b.ymin], [b.xmax, b.ymin], [b.xmax, b.ymax], [b.xmin, b.ymax], [b.xmin, b.ymin]];
        h.push(h[0]);
        return h;
      }

      // The path of the chosen file, built once per file / correction / colouring (not per zoom: the strokes are in screen pixels,
      // TT_STROKE_PX of 47-job.js). Each run keeps what it shows now (sig: opacity and how many points), so a redraw of the map or a step of
      // the simulation only touches the runs that change (2026-10-24: every redraw rewrote the points of every run).
      function tvVisBuildLayer(tvs) {
        var c = tvVisCorrection(tvs);
        var g = document.createElementNS("http://www.w3.org/2000/svg", "g");
        var runs = [];
        (tvs.prev.segments || []).forEach(function (r) {
          var pts = [];
          for (var i = 0; i < r.p.length; i += 2) pts.push((r.p[i] - c.cx) + "," + -(r.p[i + 1] - c.cy));
          var el = document.createElementNS("http://www.w3.org/2000/svg", "polyline");
          el.setAttribute("points", pts.join(" "));
          el.setAttribute("fill", "none");
          el.setAttribute("stroke", tvVisColorOf(tvs, r));
          el.setAttribute("vector-effect", "non-scaling-stroke");
          el.setAttribute("stroke-width", r.w ? TT_STROKE_PX.done : TT_STROKE_PX.travel);
          el.setAttribute("stroke-linejoin", "round");
          if (!r.w) el.setAttribute("stroke-dasharray", TT_STROKE_PX.dash);
          g.appendChild(el);
          runs.push({ el: el, run: r, pts: pts, shown: -1, sig: "" });
        });
        return { key: tvVisLayerKey(tvs, c), g: g, runs: runs, c: c };
      }

      function tvVisLayerKey(tvs, c) {
        return [tvs.sel, c.cx, c.cy, tvs.prev.vertices, tvs.colorBy].join("|");
      }

      // shows a run with this opacity and its first k + 1 points (k < 0: all); nothing is written when it already shows that
      function tvVisRunShow(o, opacity, k) {
        var sig = opacity + "|" + k;
        if (o.sig === sig) return;
        o.sig = sig;
        o.el.setAttribute("stroke-opacity", opacity);
        if (k === o.shown) return;
        o.shown = k;
        o.el.setAttribute("points", k < 0 ? o.pts.join(" ") : o.pts.slice(0, k + 1).join(" "));
      }

      function tvVisDraw(tvs, node, w) {
        if (!tvs.ctx.visible()) return;
        tvVisDrawBoard(tvs, node, w);
        if (!tvs.prev) return;
        if (!tvs.layer || tvs.layer.key !== tvVisLayerKey(tvs, tvVisCorrection(tvs))) tvs.layer = tvVisBuildLayer(tvs);
        var c = tvs.layer.c;
        var sw = w / 300;
        var simulando = tvs.tNow > 0 || tvs.playing;
        tvs.layer.runs.forEach(function (o) {
          var r = o.run;
          var base = r.w ? 0.95 : 0.5;
          var gOc = tvVisGroupOf(tvs, r);
          if (gOc && tvs.hidden[gOc.key]) return tvVisRunShow(o, 0, o.shown);
          if (!simulando) return tvVisRunShow(o, base, -1);
          var t0 = r.t ? r.t[0] : 0, t1 = r.t ? r.t[r.t.length - 1] : 0;
          if (t1 <= tvs.tNow) tvVisRunShow(o, base, -1);
          else if (t0 >= tvs.tNow) tvVisRunShow(o, base * 0.18, -1);
          else tvVisRunShow(o, base, tvVisIndexEn(tvs, r, tvs.tNow)); // the run in progress: the part done at full strength (a second line draws the rest dim)
        });
        var g = tvs.layer.g;
        // each frame the map is rebuilt: the cached lines are moved in again
        var holder = node("g", {});
        holder.appendChild(g);
        // rest of the run in progress, dim
        if (simulando) {
          var pos = tvVisPositionNow(tvs);
          if (pos) {
            var r2 = pos.run, k2 = tvVisIndexEn(tvs, r2, tvs.tNow);
            var rest = [];
            rest.push((pos.x - c.cx) + "," + -(pos.y - c.cy));
            for (var i = k2 + 1; i < r2.p.length / 2; i++) rest.push((r2.p[2 * i] - c.cx) + "," + -(r2.p[2 * i + 1] - c.cy));
            if (rest.length > 1 && r2.t[r2.t.length - 1] > tvs.tNow) {
              node("polyline", { points: rest.join(" "), fill: "none", stroke: tvVisColorOf(tvs, r2), "stroke-width": sw * (r2.w ? 1.5 : 0.7), "stroke-opacity": 0.18, "stroke-linejoin": "round" });
            }
            node("circle", { cx: pos.x - c.cx, cy: -(pos.y - c.cy), r: w / 90, fill: pos.run.w && (tvs.prev.mode !== "Laser" || pos.run.v > 0) ? "#ff1744" : "none", stroke: "#fff", "stroke-width": sw });
          }
        }
        // the outline that "Frame" would trace (where the pointer will pass if the pointer is chosen)
        var of = tvvisforma_points(tvs);
        if (of.length) {
          var pts = of.map(function (p) {
            var dx = tvs.how === "pointer" ? 0 : 0; // the outline is drawn where the BEAM will go, in both ways
            return (p[0] - c.cx + dx) + "," + -(p[1] - c.cy);
          });
          node("polyline", { points: pts.join(" "), fill: "none", stroke: "#26c6da", "stroke-width": sw * 1.4, "stroke-dasharray": w / 90 + " " + w / 140, "stroke-opacity": 0.95 });
        }
      }

      // ---------- the frame ----------
      // NOT a job: the service sends short pieces (frame.start) and stops at once (frame.stop), once, N times or until stopped
      function tvVisWatchFrame(tvs) {
        clearInterval(tvs.frameTimer);
        tvs.frameTimer = setInterval(function () {
          workshopApi("frame.status", {}).then(function (e) {
            var before = tvs.frameSt && tvs.frameSt.active;
            tvs.frameSt = e;
            if (!e.active) {
              clearInterval(tvs.frameTimer);
              tvs.frameTimer = null;
              if (before) {
                tvs.msgOk = !e.error;
                tvs.msg = e.error ? e.error : e.finished === "stopped" ? i18nT('tv.framing_stopped') : i18nT('tv.framing_done');
              }
            }
            if (tvs.ctx.visible()) tvVisRender(tvs);
          }).catch(function () {});
        }, 1000);
      }

